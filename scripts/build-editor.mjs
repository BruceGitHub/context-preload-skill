#!/usr/bin/env node
/**
 * CRC · scripts/build-editor
 *
 * Scopo: costruire l'editor in un unico file HTML, rimuovendo i tipi dal core
 * e inlinando core + UI nel template.
 * Collaboratori: src/crf-core.ts, editor/template.html, editor/editor.js,
 * node:module (`stripTypeScriptTypes`), node:fs, node:path.
 * Consumatori: `npm run build:editor`, la CI e editor/index.html.
 */

import fs from 'node:fs';
import path from 'node:path';
import { stripTypeScriptTypes } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(ROOT, relative), 'utf8');
const write = (relative, content) => fs.writeFileSync(path.join(ROOT, relative), content);

const template = read('editor/template.html');
const core = stripTypeScriptTypes(read('src/crf-core.ts'), { mode: 'strip' });
const editor = read('editor/editor.js');

for (const placeholder of ['/*__CRF_CORE__*/', '/*__EDITOR__*/']) {
  if (!template.includes(placeholder)) {
    throw new Error(`editor/template.html is missing ${placeholder}`);
  }
}

// The core is written as an ES module for Node. Inlined into the editor it
// lives in the same module scope, so the export keyword can be dropped.
const inlinedCore = core.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/gm, '');

const banner =
  '<!-- Generated by scripts/build-editor.mjs — edit editor/template.html and editor/editor.js instead. -->';

const html = template
  .replace('/*__CRF_CORE__*/', () => inlinedCore)
  .replace('/*__EDITOR__*/', () => editor)
  .replace('<!DOCTYPE html>', () => `<!DOCTYPE html>\n${banner}`);

write('editor/index.html', html);

const bytes = Buffer.byteLength(html);
console.log(`built editor/index.html (${(bytes / 1024).toFixed(1)} kB)`);
